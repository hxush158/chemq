from chemq.rag import HYBRID_SQL, Hit, hybrid_search, is_no_hit  # noqa: F401

# 决定 1：`折标煤系数依据哪个标准` -> 答案里的关键 token 是 "GB/T 2589"。
# 向量模型会把它压成一个"标准编号"的模糊表示，和 "GB/T 50034" 几乎分不开；
# BM25 则是精确字符串匹配，一击即中。反过来 "能耗怎么算" 这种问法没有共同词，
# BM25 全靠运气，向量才行。两种失败模式互补，所以要 hybrid。
#
# ⚠ 前提是 BM25 真的能切中文。PostgreSQL 的 to_tsvector('simple', ...) 不切中文，
#   一整句会变成一个词项 —— 这一路在中文上等于没开。见 chemq/textseg.py。

# 决定 2：RRF 的 k 是"名次的钝化程度"。
#   k=1    第 1 名 0.5、第 2 名 0.33 —— 头部权重极大，一路召回说了算，等于没融合
#   k=1000 第 1 名和第 20 名几乎一样 —— 名次信息被抹平，退化成"出现在两路里就行"
#   k=60   源自 RRF 原论文的经验值，在"尊重名次"和"允许另一路翻盘"之间比较平衡
# 这个参数值得你自己在 evals 上扫一遍 [10, 30, 60, 100]，看 Recall@5 怎么动。

# 决定 3：检索到了但仍要拒答的两种情况 ——
#   a) 召回的都是弱相关：勉强作答就是在编。
#   b) top-1 和 top-2 指向互相矛盾的口径版本：要把矛盾报出来让人裁决，
#      而不是挑一个说得更顺的。口径冲突在数据治理项目里极其常见。
#
# ❌ 反面教材：这个文件原来对 a) 的实现是
#
#        if not rows or rows[0]["score"] < 1 / (RRF_K + 10):
#            return []
#
#    它用 RRF 分数当相关度阈值。但 RRF 分数只是名次：向量检索永远会返回最近的 N 条，
#    第一名永远拿 1/(60+1) ≈ 0.0164 > 1/70 —— 问"帮我写辞职信"也照样"检索到"，
#    这个拒答分支永远不会触发。正确做法见 rag.is_no_hit()：看原始余弦相似度，
#    再加上"问题里的标识符有没有被字面命中"。
#
#    原来的 SQL 还有一个问题：`row_number() OVER (ORDER BY ...) ... LIMIT 20` 没有外层
#    ORDER BY，LIMIT 取到的不保证是前 20 名，而且用不上 HNSW 索引。
